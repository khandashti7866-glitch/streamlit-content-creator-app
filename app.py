def translate_to_urdu_fallback(text: str) -> str:
    """Naive word-by-word translation using small dictionary fallback."""
    def tr_word(w):
        key = re.sub(r"[^a-zA-Z]", "", w).lower()
        if key in URDU_DICT:
            return URDU_DICT[key]
        return w
    return " ".join(tr_word(w) for w in text.split())


