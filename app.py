def clean_text(text: str) -> str:
    """Simple text cleaning."""
    return re.sub(r"\s+", " ", text).strip()


def extract_keywords(topic: str, max_keywords: int = 6) -> List[str]:
    """Very simple keyword extractor: split on non-words, filter stopwords and short tokens."""
    tokens = re.findall(r"\w+", topic.lower())
    tokens = [t for t in tokens if t not in STOPWORDS and len(t) > 2]
    if not tokens:
        # fallback: use words of topic
        tokens = re.findall(r"\w+", topic.lower())
    # prefer unique preserving order
    seen = set()
    kws = []
    for t in tokens:
        if t not in seen:
            seen.add(t)
            kws.append(t)
        if len(kws) >= max_keywords:
            break
    return kws


def generate_hashtags_from_keywords(keywords: List[str], desired: int = 8) -> List[str]:
    """Produce relevant-looking hashtags from keywords and simple rules."""
    tags = []
    for kw in keywords:
        base = re.sub(r"[^a-zA-Z0-9]", "", kw)
        if not base:
            continue
        # produce a few variants
        variants = [f"#{base}", f"#{base}tips", f"#{base}life", f"#{base}hack"]
        for v in variants:
            if v not in tags:
                tags.append(v)
            if len(tags) >= desired:
                break
        if len(tags) >= desired:
            break
    # ensure we have at least 5 tags
    extra = ["#viral", "#trending", "#learn", "#howto", "#tips"]
    i = 0
    while len(tags) < 5 and i < len(extra):
        tags.append(extra[i])
        i += 1
    return tags[:desired]


def truncate_to_length(text: str, max_chars: int) -> str:
    """Truncate gracefully at word boundary."""
    text = clean_text(text)
    if len(text) <= max_chars:
        return text
    # Try to cut at nearest sentence end before max_chars
    cut = text[:max_chars]
    last_period = cut.rfind(".")
    if last_period > int(max_chars * 0.6):
        return cut[: last_period + 1]
    # else cut at last space
    last_space = cut.rfind(" ")
    if last_space > 0:
        return cut[:last_space] + "…"
    return cut[:max_chars] + "…"


def estimate_reading_time(text: str) -> str:
    """Return estimated reading time as string (seconds or minutes)."""
    words = len(re.findall(r"\w+", text))
    wpm = 200  # words per minute
    minutes = words / wpm
    if minutes < 0.5:
        seconds = int(minutes * 60)
        return f"{seconds} sec"
    else:
        return f"{minutes:.1f} min"


