def make_funnier(text: str) -> str:
    """A simple deterministic 'make funnier' transformation (insert emoji, exaggerate)."""
    punchlines = ["😂", "😅", "🔥"]
    # insert a casual punchline at end of first sentence
    parts = re.split(r'([.!?])', text, maxsplit=1)
    if parts and len(parts) >= 1:
        first = parts[0]
        remainder = "".join(parts[1:]) if len(parts) > 1 else ""
        first = first + " " + np.random.choice(punchlines)
        return (first + remainder).strip()
    return text + " " + np.random.choice(punchlines)


def replace_synonyms(text: str) -> str:
    """Replace some words with synonyms deterministically."""
    words = text.split()
    new_words = []
    for w in words:
        key = re.sub(r"[^a-zA-Z]", "", w).lower()
        if key in SYNONYMS_SIMPLE:
            new_words.append(np.random.choice(SYNONYMS_SIMPLE[key]))
        else:
            new_words.append(w)
    return " ".join(new_words)


