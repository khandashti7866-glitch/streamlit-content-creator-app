def model_generate(prompt: str, max_length: int = 120, num_return_sequences: int = 1) -> List[str]:
    """Use transformer model to generate text (if available)."""
    if not MODEL_AVAILABLE or _model is None or _tokenizer is None:
        raise RuntimeError("Model not available")
    device = "cuda" if torch.cuda.is_available() else "cpu"
    _model.to(device)
    inputs = _tokenizer(prompt, return_tensors="pt").to(device)
    # keep generation conservative
    out = _model.generate(
        **inputs,
        max_length=min(max_length + len(inputs["input_ids"][0]), 400),
        do_sample=True,
        top_p=0.9,
        temperature=0.9,
        num_return_sequences=num_return_sequences,
        pad_token_id=_tokenizer.eos_token_id
    )
    results = []
    for o in out:
        txt = _tokenizer.decode(o, skip_special_tokens=True)
        # strip prompt prefix
        if txt.startswith(prompt):
            txt = txt[len(prompt):].strip()
        results.append(clean_text(txt))
    return results


