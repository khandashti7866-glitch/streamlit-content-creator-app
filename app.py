def generate_variants(
    topic: str,
    platform: str,
    tone: str,
    length_pref: str,
    n_variations: int,
    target_keywords: str = ""
) -> List[Dict[str, Any]]:
    """Generate content variants. Always returns at least one variant."""
    topic_clean = clean_text(topic)
    keywords = extract_keywords(topic_clean, max_keywords=6)
    # Add user-provided keywords
    if target_keywords:
        user_kws = [k.strip("# ").lower() for k in re.split(r"[,\n;]+", target_keywords) if k.strip()]
        for uk in user_kws:
            if uk and uk not in keywords:
                keywords.insert(0, uk)
    # Determine character target
    char_limit = PLATFORM_CHARACTER_LIMITS.get(platform, 300)
    if length_pref == "Short (<=120 chars)":
        target_chars = 120
    elif length_pref == "Medium (120–300 chars)":
        target_chars = 300
    else:
        target_chars = min(800, char_limit)

    variants: List[Dict[str, Any]] = []
    # If model available, try to use it; otherwise fallback templates
    use_model = MODEL_AVAILABLE and _model is not None and _tokenizer is not None

    for i in range(max(1, n_variations)):
        try:
            if use_model:
                # Build a simple prompt
                prompt = (
                    f"Write a {tone.lower()} social media post about: {topic_clean}. "
                    f"Platform: {platform}. Length target chars: {target_chars}. "
                    f"Include a short hook, body, CTA, hashtags and a 2-line short video script.\n\nPost:\n"
                )
                outs = model_generate(prompt, max_length=min(400, target_chars + 120), num_return_sequences=1)
                post_text = outs[0] if outs else ""
                post_text = truncate_to_length(post_text, target_chars)
                confidence = min(0.95, 0.5 + 0.05 * len(post_text) / (target_chars + 1))
                confidence_label = f"model (conf {confidence:.2f})"
            else:
                # deterministic fallback
                # Choose templates by rotation
                hook_tpl = np.random.choice(HOOK_TEMPLATES)
                cta_tpl = np.random.choice(CTA_TEMPLATES)
                img_tpl = np.random.choice(IMAGE_PROMPTS)
                vscripts = np.random.choice(VIDEO_SCRIPT_TEMPLATES)
                # simple action placeholder
                action = "save time" if "save" in topic_clean.lower() else "get better results"
                hook = hook_tpl.format(topic=topic_clean, action=action)
                body_templates = [
                    f"{topic_clean} can be easier than you think. Here's a simple way: 1) Do this 2) Do that. {cta_tpl}",
                    f"Want to improve {topic_clean}? Start with a small habit: try this today. {cta_tpl}",
                    f"Short guide on {topic_clean}: avoid common mistakes and focus on one skill each day. {cta_tpl}"
                ]
                body = np.random.choice(body_templates).format(topic=topic_clean)
                post_text = f"{hook} {body}"
                post_text = truncate_to_length(post_text, target_chars)
                confidence_label = "template"
            # Hashtags and other props
            kws_for_tags = keywords if keywords else extract_keywords(topic_clean, max_keywords=4)
            hashtags = generate_hashtags_from_keywords(kws_for_tags, desired=8)
            first_line_hook = hook if 'hook' in locals() else truncate_to_length(post_text.split(".")[0], 80)
            cta = cta_tpl if 'cta_tpl' in locals() else np.random.choice(CTA_TEMPLATES)
            image_prompt = img_tpl.format(topic=topic_clean) if 'img_tpl' in locals() else f"Photo representing {topic_clean}"
            video_script = vscripts.format(hook=first_line_hook, topic=topic_clean, action=action) if 'vscripts' in locals() else f"{first_line_hook}\nShow steps quickly.\n{cta}"
            # posting time - simple rule
            best_day, best_hour = PLATFORM_BEST_TIMES.get(platform, ("Monday", 12))
            # Add slight variance
            best_hour_v = (best_hour + i) % 24
            suggested_datetime = f"{best_day} at {best_hour_v}:00"
            # stats
            char_count = len(post_text)
            read_time = estimate_reading_time(post_text)

            variants.append(
                {
                    "id": f"v{i+1}",
                    "post_text": post_text,
                    "hashtags": hashtags,
                    "first_line_hook": first_line_hook,
                    "cta": cta,
                    "image_prompt": image_prompt,
                    "video_script": video_script,
                    "posting_time": suggested_datetime,
                    "char_count": char_count,
                    "reading_time": read_time,
                    "confidence": confidence_label,
                    "platform": platform,
                    "tone": tone,
                }
            )
        except Exception as e:
            # Robust fallback: ensure at least one variant is returned even on error
            variants.append(
                {
                    "id": f"v{i+1}",
                    "post_text": f"{topic_clean} — quick tip. {np.random.choice(CTA_TEMPLATES)}",
                    "hashtags": ["#tip", "#social"],
                    "first_line_hook": topic_clean,
                    "cta": np.random.choice(CTA_TEMPLATES),
                    "image_prompt": f"Illustration of {topic_clean}",
                    "video_script": f"Hook: {topic_clean}\nAction: Show example\nCTA: Comment",
                    "posting_time": f"Anytime",
                    "char_count": 50,
                    "reading_time": "10 sec",
                    "confidence": "template",
                    "platform": platform,
                    "tone": tone,
                }
            )
    return variants


